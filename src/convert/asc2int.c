#include "common.h"
#include "asc2int.h"
#include "symtab.h"

/**
 * 문자 상수 → 정수 변환 (ap = ASCII Pointer)   예) "'AB'" → 0x4142
 * - 마지막 글자가 닫는 따옴표(')가 아니면 변환 실패(INV_VAL) 반환
 * - 여는 따옴표 다음 글자부터 닫는 따옴표 앞까지 한 글자씩 읽어 -> 아스키 코드를 1바이트씩 차례로 쌓기
 * - int는 4바이트라 최대 4글자까지 담김 (5글자부터는 앞 글자가 밀려나 사라짐)
 */
int asc2int(char* ap) {
    int l = strlen(ap);
    int v;

    if (ap[l - 1] != '\'') {               // 닫는 따옴표로 끝나지 않으면 문자 상수가 아님
        return INV_VAL;
    }

    for (v = 0; *(ap + 1) != '\''; ap++) { // 다음 글자가 닫는 따옴표(')이면 종료 (ap[0]은 여는 따옴표라 건너뜀)
        v = (v << 8) | *(ap + 1);          // 8비트(1바이트) 밀어 맨 아래 칸을 비우고 다음 글자의 아스키 코드를 끼워 넣기
                                           // 'AB' → 0x41 → 0x4142
    }
    return v;                              // 쌓인 값 반환 ('AB' → 0x00004142)
}